"""
Russian -> Ukrainian word list, for the `uk` labels of the ported modules.

The same idea as `terms.py`, and deliberately the same keys: the 1C synonyms are Russian
noun phrases built from a known vocabulary, so translating them word by word produces the
Ukrainian phrase. Because the keys are inflected Russian forms, the values can be the
matching inflected Ukrainian forms - `материалов` (genitive plural) becomes `матеріалів`,
`материал` becomes `матеріал` - which is what keeps `Расход материалов` from turning into
`Витрата матеріали`.

Unlike the English side, prepositions are translated rather than dropped: `Цены по
складам` is `Ціни по складах`, and a label that reads as a phrase has to keep its glue.

This is generated vocabulary, not authored prose. It should be read once by someone who
speaks Ukrainian - `tools/i18n_coverage.py` and `tools/validate.py` say which modules are
covered, and the three hand-written modules (fleet, shipping, masterdata) keep their
authored wording, which always wins over anything derived here.
"""

